"""Myna's original 5x7 dot-matrix font for the Amber VFD theme.

Each glyph is 7 rows of 5 columns ("#" = lit); g j p q y µ (and a few
punctuation marks) carry 2 more descender rows. Rows 0-6 are the cap height;
lowercase sits on rows 2-6; descenders use rows 7-8."""

G: dict[str, str] = {}


def g(chars: str, art: str) -> None:
    rows = [row for row in art.strip("\n").split("\n")]
    rows = [row.strip() for row in rows]
    assert len(rows) in (7, 9), (chars, len(rows))
    assert all(len(row) == 5 and set(row) <= {"#", "."} for row in rows), (chars, rows)
    for ch in chars:
        G[ch] = "\n".join(rows)


